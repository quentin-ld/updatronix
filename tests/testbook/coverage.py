#!/usr/bin/env python3
"""Generate the implemented/pending coverage report from the catalog and run.py."""

from __future__ import annotations

import re
from collections import Counter, defaultdict
from pathlib import Path

import yaml

TB = Path(__file__).resolve().parent
ROOT = TB.parents[1]
RUN = (TB / "run.py").read_text(encoding="utf-8")
IMPLEMENTED = set(re.findall(r'"(TB-[A-Z]+-\d{3})"\s*:\s*BookCase', RUN))
OUT = ROOT / "docs/testing/test-book-coverage.md"

cases = []
for name, keys in (
    ("cases.yaml", ("surface_cases", "flow_cases", "triples")),
    ("cases.generated.yaml", ("cases",)),
    ("pro/cases.yaml", ("cases",)),
):
    data = yaml.safe_load((TB / name).read_text(encoding="utf-8"))
    for key in keys:
        for case in data.get(key, []) or []:
            if "id" in case:
                cases.append(case)

pending = [c for c in cases if c["id"] not in IMPLEMENTED]
risks = ("critical", "high", "medium", "low")
lines = [
    "<!-- generated by tests/testbook/coverage.py; do not edit -->",
    "# Test-book coverage",
    "",
    f"Catalog: **{len(cases)} cases**. Implemented executors: **{len(IMPLEMENTED)}**. "
    f"Pending: **{len(pending)}**.",
    "",
    "This report is generated from the catalog and the `CASES` registry in",
    "`tests/testbook/run.py`. It is a coverage statement, not a green claim: a",
    "pending case has no executor and cannot pass a gate.",
    "",
    "## By risk",
    "",
    "| Risk | Total | Implemented | Pending |",
    "|---|---:|---:|---:|",
]
for risk in risks:
    total = sum(1 for c in cases if c.get("risk") == risk)
    done = sum(1 for c in cases if c.get("risk") == risk and c["id"] in IMPLEMENTED)
    lines.append(f"| {risk} | {total} | {done} | {total - done} |")
lines += ["", "## Implemented", ""]
for case_id in sorted(IMPLEMENTED):
    case = next((c for c in cases if c["id"] == case_id), None)
    lines.append(f"- `{case_id}` — {case.get('title', 'not in catalog') if case else 'not in catalog'}")
lines += [
    "",
    "## Pending critical and high",
    "",
    "| ID | Risk | Title | Tags |",
    "|---|---|---|---|",
]
for case in pending:
    if case.get("risk") not in ("critical", "high"):
        continue
    tags = " ".join(case.get("tags", []))
    lines.append(f"| `{case['id']}` | {case.get('risk')} | {case.get('title', '')} | {tags} |")
lines += ["", "## By tag", "", "| Tag | Total | Pending |", "|---|---:|---:|"]
tag_total = Counter()
tag_pending = Counter()
for case in cases:
    for tag in case.get("tags", []):
        tag_total[tag] += 1
        if case["id"] not in IMPLEMENTED:
            tag_pending[tag] += 1
for tag in sorted(tag_total):
    lines.append(f"| {tag} | {tag_total[tag]} | {tag_pending[tag]} |")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(IMPLEMENTED)} implemented, {len(pending)} pending; wrote {OUT}")
