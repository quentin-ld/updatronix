#!/usr/bin/env python3
"""Generate the implemented/pending coverage report from `run.py --list --json`.

The registry is the only source of truth for implementation: the report never
scans source text, so a registration refactor cannot silently undercount.
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

TB = Path(__file__).resolve().parent
ROOT = TB.parents[1]
OUT = ROOT / "docs/testing/test-book-coverage.md"


def registry() -> dict:
	completed = subprocess.run(
		[ sys.executable, str( TB / "run.py" ), "--list", "--json" ],
		cwd=ROOT,
		text=True,
		capture_output=True,
	)
	if completed.returncode != 0:
		raise RuntimeError(
			"run.py --list --json failed: "
			f"{completed.stderr.strip() or completed.stdout.strip()}"
		)
	return json.loads( completed.stdout )


def main() -> int:
	data = registry()
	cases = data["cases"]
	implemented = { case["id"] for case in cases if case["implemented"] }
	partial = { case["id"] for case in cases if case["partial"] }
	pending = [ case for case in cases if not case["implemented"] ]
	risks = ( "critical", "high", "medium", "low" )

	lines = [
		"<!-- generated by tests/testbook/coverage.py; do not edit -->",
		"# Test-book coverage",
		"",
		f"Catalog: **{len(cases)} cases**. Implemented executors: **{len(implemented)}** "
		f"({len(partial)} partial). Pending: **{len(pending)}**.",
		"",
		"This report is generated from `run.py --list --json`, the same registry",
		"the gates execute. It is a coverage statement, not a green claim: a",
		"pending case has no executor and cannot pass a gate.",
		"",
		"## By risk",
		"",
		"| Risk | Total | Implemented | Partial | Pending |",
		"|---|---:|---:|---:|---:|",
	]
	for risk in risks:
		total = sum( 1 for case in cases if case.get( "risk" ) == risk )
		done = sum( 1 for case in cases if case.get( "risk" ) == risk and case["implemented"] )
		part = sum( 1 for case in cases if case.get( "risk" ) == risk and case["partial"] )
		lines.append( f"| {risk} | {total} | {done - part} | {part} | {total - done} |" )

	lines += [ "", "## Implemented", "" ]
	for case_id in sorted( implemented ):
		case = next( item for item in cases if item["id"] == case_id )
		suffix = " (partial)" if case_id in partial else ""
		lines.append( f"- `{case_id}` — {case.get('title', '') }{suffix}" )

	lines += [
		"",
		"## Pending critical and high",
		"",
		"| ID | Risk | Title | Tags |",
		"|---|---|---|---|",
	]
	for case in pending:
		if case.get( "risk" ) not in ( "critical", "high" ):
			continue
		tags = " ".join( case.get( "tags", [] ) )
		lines.append( f"| `{case['id']}` | {case.get( 'risk' )} | {case.get( 'title', '' )} | {tags} |" )

	lines += [ "", "## By tag", "", "| Tag | Total | Pending |", "|---|---:|---:|" ]
	tag_total = Counter()
	tag_pending = Counter()
	for case in cases:
		for tag in case.get( "tags", [] ):
			tag_total[ tag ] += 1
			if not case["implemented"]:
				tag_pending[ tag ] += 1
	for tag in sorted( tag_total ):
		lines.append( f"| {tag} | {tag_total[tag]} | {tag_pending[tag]} |" )

	OUT.parent.mkdir( parents=True, exist_ok=True )
	OUT.write_text( "\n".join( lines ) + "\n", encoding="utf-8" )
	print( f"{len(implemented)} implemented ({len(partial)} partial), {len(pending)} pending; wrote {OUT}" )
	return 0


if __name__ == "__main__":
	sys.exit( main() )
